"""Dataset audit script — Week 1 day 1 task.

For each candidate dataset, verify:
  1. Image count matches listing
  2. License is recorded
  3. 20 random images pass eyeball check (manual review)
  4. Class balance / annotation format is as advertised
  5. No duplicate vehicles (hash plate region)

Outputs DATA_PROVENANCE.md entries.

Usage:
  python -m scripts.audit_datasets --root data/ --out DATA_PROVENANCE.md
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import logging
import random
import sys
from collections import Counter
from pathlib import Path

logger = logging.getLogger(__name__)


def hash_image(path: Path) -> str:
    """Perceptual-ish hash — just SHA256 of the raw bytes for dedup."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:16]


def audit_one(dataset_dir: Path) -> dict:
    """Audit one dataset directory. Returns a report dict."""
    images_dir = dataset_dir / "images"
    if not images_dir.exists():
        # Try a direct glob — some datasets don't have an images/ subdir.
        candidates = list(dataset_dir.glob("*.jpg")) + list(dataset_dir.glob("*.png"))
        if not candidates:
            return {"name": dataset_dir.name, "error": "no images found"}
        images_dir = dataset_dir
    images = sorted(list(images_dir.glob("*.jpg")) + list(images_dir.glob("*.png")))
    report = {
        "name": dataset_dir.name,
        "path": str(dataset_dir),
        "n_images": len(images),
        "duplicate_hashes": 0,
        "unique_hashes": 0,
    }
    if not images:
        report["error"] = "no images"
        return report
    # Hash dedup — limit to 1000 random images for speed on large sets.
    sample = random.sample(images, min(1000, len(images)))
    hashes = Counter(hash_image(p) for p in sample)
    report["unique_hashes"] = sum(1 for c in hashes.values() if c == 1)
    report["duplicate_hashes"] = len(hashes) - report["unique_hashes"]
    # Sample 20 random images for manual eyeball check
    report["eyeball_sample"] = [str(p) for p in random.sample(images, min(20, len(images)))]
    return report


def audit_all(root: Path) -> list[dict]:
    reports = []
    for ds in sorted(root.iterdir()):
        if ds.is_dir() and not ds.name.startswith("."):
            logger.info("auditing %s", ds)
            reports.append(audit_one(ds))
    return reports


def render_provenance(reports: list[dict]) -> str:
    """Render DATA_PROVENANCE.md content from audit reports."""
    lines = ["# Data Provenance\n",
             "Auto-generated by `scripts/audit_datasets.py`.",
             "Extend each entry manually with the license, source URL, and curation notes.\n",
             "## Datasets\n"]
    for r in reports:
        lines.append(f"### {r['name']}\n")
        if "error" in r:
            lines.append(f"- **ERROR**: {r['error']}\n")
            continue
        lines.append(f"- Path: `{r['path']}`")
        lines.append(f"- Images: {r['n_images']}")
        lines.append(f"- Sampled hashes: unique={r['unique_hashes']}, "
                     f"likely_duplicates={r['duplicate_hashes']}")
        lines.append(f"- License: TODO (fill in)")
        lines.append(f"- Source URL: TODO (fill in)")
        lines.append(f"- Curation notes: TODO (eyeball the 20 sample images listed below)")
        lines.append(f"- Eyeball sample:")
        for s in r.get("eyeball_sample", []):
            lines.append(f"  - `{s}`")
        lines.append("")
    lines.append("## License Notes\n")
    lines.append("- **Ultralytics YOLO11/YOLO26**: AGPL-3.0 base. For commercial use, "
                 "buy an Ultralytics Enterprise license.")
    lines.append("- **PARSeq**: MIT.")
    lines.append("- **Real-ESRGAN**: Apache-2.0.")
    lines.append("- **PaddleOCR**: Apache-2.0.")
    lines.append("- **ByteTrack / supervision**: MIT.")
    lines.append("- **CCPD**: academic use only — cite Xu et al. 2018.")
    lines.append("- **Roboflow Universe sets**: per-dataset, mostly CC-BY-4.0.")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Audit datasets")
    p.add_argument("--root", type=Path, default=Path("data"))
    p.add_argument("--out", type=Path, default=Path("DATA_PROVENANCE.md"))
    args = p.parse_args(argv)
    logging.basicConfig(level=logging.INFO,
                        format="%(levelname)s: %(message)s")
    if not args.root.exists():
        logger.error("root not found: %s", args.root)
        return 1
    reports = audit_all(args.root)
    args.out.write_text(render_provenance(reports))
    logger.info("wrote %s with %d entries", args.out, len(reports))
    return 0


if __name__ == "__main__":
    sys.exit(main())
